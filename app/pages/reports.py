"""Reports.

The business-facing artefact: an executive summary, the KPI picture, findings,
risk, quality and SQL verification, plus export. The page renders the *same*
report object a scheduled run would email, so what is previewed is what ships.
"""

from __future__ import annotations

import datetime as dt
