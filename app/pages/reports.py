import pandas as pd
import streamlit as st

from components import cards, layout, tables
from styles.theme import COLORS

import insights as insight_adapters


def _build_context(ctx) -> Any:
    from src.reporting import ReportContext

    result = ctx.result
    retention = result.analyses.get("retention")
    segmentation = result.analyses.get("segmentation", {}) or {}
    answers = result.analyses.get("answers")
    answers_list = (
        [a for a in answers.to_dict("records")] if isinstance(answers, pd.DataFrame) else (answers or [])
    )
    return ReportContext(
        kpis=ctx.kpis,
        retention=retention.summary if retention else {},
        retention_comparison=retention.comparison if retention else pd.DataFrame(),
        segment_metrics=segmentation.get("metrics", pd.DataFrame()),
        segment_insight=segmentation.get("insight", ""),
        trend_summary=result.analyses.get("trend_summary", {}),
        monthly_trend=result.analyses.get("monthly_trend", pd.DataFrame()),
        engagement=result.analyses.get("engagement", {}),
        anomalies=result.analyses.get("anomalies", pd.DataFrame()),
        alerts=result.alerts,
        alert_summary=result.analyses.get("alert_summary", {}),
        quality=(result.quality or {}).get("summary", {}),
        quality_checks=(result.quality or {}).get("checks", pd.DataFrame()),
        crosscheck=result.validation.get("crosscheck", pd.DataFrame()),
        integrity=result.validation.get("integrity", pd.DataFrame()),
        answers=_hydrate_answers(answers_list),
        root_causes=result.analyses.get("root_cause_chains", []),
        integration=result.integration or {},
        funnel=result.analyses.get("platform_funnel", pd.DataFrame()),
        funnel_insight=result.analyses.get("funnel_insight", ""),
        sources=(result.metadata or {}).get("sources", {}),
        metadata=result.metadata or {},
        stage_records=result.stage_records,
    )


def _hydrate_answers(rows: List[dict]) -> list:
    """Rebuild lightweight answer objects from the stored answer table."""
    from dataclasses import dataclass, field

    @dataclass
    class _Answer:
        question_id: str
        question: str
        answer: str
        evidence: List[str] = field(default_factory=list)
        provenance: str = "real"
        caveats: List[str] = field(default_factory=list)
        available: bool = True

    hydrated = []
    for row in rows:
        if not isinstance(row, dict):
            hydrated.append(row)
            continue
        hydrated.append(
            _Answer(
                question_id=str(row.get("question_id", row.get("id", ""))),
                question=str(row.get("question", "")),
                answer=str(row.get("answer", "")),
                evidence=[item for item in str(row.get("evidence", "")).split(" | ") if item],
                provenance=str(row.get("provenance", "real")),
                caveats=[item for item in str(row.get("caveats", "")).split(" | ") if item],
                available=bool(row.get("available", True)),
            )
        )
    return hydrated


def render(ctx) -> None:
    result = ctx.result
    kpis = ctx.kpis
    quality = (result.quality or {}).get("summary", {}) or {}
    validation = (result.validation or {}).get("summary", {}) or {}
    alerts = result.analyses.get("alert_summary", {}) or {}
    segmentation = result.analyses.get("segmentation", {}) or {}

    layout.page_header(
        "Executive Report",
        "The board-ready summary: retention health, the findings behind it, risk, data quality and "
        "independent SQL verification. Generated by the analytical layer, not authored in the UI.",
        icon_name="description",
        eyebrow="Reporting",
    )

    _report_header(result, kpis, quality, validation, alerts)
    _key_findings(result)
    _section_summaries(kpis, segmentation, alerts, quality, validation)
    _generate_and_export(ctx, result)


