    "triangle-alert", "gauge", "target", "timer", "footprints", "heart-pulse",
    "calendar-check", "refresh-cw", "zap", "shield-check", "scale", "crosshair",
    "circle-dot",
    # status + feedback
    "circle-check", "circle-alert", "circle-x", "info", "arrow-up-right",
    "arrow-down-right", "minus", "chevron-right", "sparkles", "lightbulb",
    # controls + io
    "filter", "search", "download", "mail", "external-link", "play",
    "rotate-ccw", "upload", "eye", "bell",
    # content
    "table", "table-2", "code", "chart-pie", "chart-column", "chart-line",
    "file-text", "clipboard-check", "list-filter", "layers", "boxes", "compass",
    "award", "badge-check", "trophy", "medal", "ruler", "repeat", "flag", "star",
