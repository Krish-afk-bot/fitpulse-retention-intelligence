def data_dictionary_frame() -> pd.DataFrame:
    """The dictionary as a DataFrame."""
    return pd.DataFrame([entry.as_dict() for entry in DATA_DICTIONARY])


def dictionary_markdown() -> str:
    """Render the dictionary as markdown documentation."""
    frame = data_dictionary_frame()
    lines = [
        "# FitPulse — Data Dictionary",
        "",
        "Every canonical field, its source field, business meaning, validation rule and "
        "provenance. `derived_or_raw` distinguishes calculated columns from source columns, and "
        "`synthetic` marks values that depend on the documented synthetic integration layer.",
        "",
        "## Source datasets",
        "",
        f"- **{ACTIVITY_SOURCE.label}** — {ACTIVITY_SOURCE.url} ({ACTIVITY_SOURCE.license})",
        f"- **{MEMBERSHIP_SOURCE.label}** — {MEMBERSHIP_SOURCE.url} ({MEMBERSHIP_SOURCE.license})",
        "",
        "## Fields",
        "",
    ]
    for row in frame.itertuples():
        lines.append(f"### `{row.field_name}`")
        lines.append("")
        lines.append(f"| Property | Value |")
        lines.append("|---|---|")
        lines.append(f"| Dataset | `{row.dataset}` |")
        lines.append(f"| Source field | `{row.source_field}` |")
        lines.append(f"| Description | {row.description} |")
        lines.append(f"| Data type | {row.data_type} |")
        lines.append(f"| Business meaning | {row.business_meaning} |")
        lines.append(f"| Allowed values | {row.allowed_values or 'n/a'} |")
        lines.append(f"| Validation rules | {row.validation_rules or 'n/a'} |")
        lines.append(f"| Example | `{row.example}` |")
        lines.append(f"| Derived or raw | {row.derived_or_raw} |")
        lines.append(f"| Synthetic | {row.synthetic} |")
        if row.limitation:
            lines.append(f"| Limitation | {row.limitation} |")
        lines.append("")
    return "\n".join(lines)


def dictionary_csv() -> pd.DataFrame:
    """Machine-readable dictionary export."""
    return data_dictionary_frame()[
        [
            "field_name",
            "dataset",
            "source_field",
            "description",
            "data_type",
            "business_meaning",
            "allowed_values",
            "validation_rules",
            "example",
            "derived_or_raw",
            "synthetic",
            "limitation",
        ]
    ]
